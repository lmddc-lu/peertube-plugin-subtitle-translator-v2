import type { RegisterClientOptions } from '@peertube/peertube-types/client'

/**
 * Adds caption translation to the video manage captions page (/videos/manage/:id/captions).
 *
 * Two parts are inserted into PeerTube's page, which has no client hook or placeholder:
 * - status rows inside the caption list, just above the "Add a caption" button, styled like
 *   PeerTube's own caption rows: one row per translation that is running, published, or failed;
 * - a "Translate captions" section after the caption list with the source / target pickers.
 *
 * PeerTube stages caption changes until the page is saved, but plugins have no access to that
 * staging, so a translated caption is uploaded right away with the user's session; the texts say
 * so. Failures show a short message only: technical details stay in the server log and the
 * browser console. Angular may re-create the caption list, so both parts are re-attached when they get detached,
 * until the user leaves this video's captions page.
 *
 * The script runs in the `common` scope because the `video-edit` scope only loads once the
 * main-info tab has been opened.
 */

type Helpers = RegisterClientOptions['peertubeHelpers']

type JobStatus =
  | 'running'
  | 'completed'
  | 'interrupted'
  | 'job_failed'
  | 'backend_unreachable'
  | 'backend_error'
  | 'invalid_response'
  | 'empty_translation'

type FailureStatus = Exclude<JobStatus, 'running' | 'completed'>

type Job = {
  status: JobStatus
  sourceLanguage: string
  targetLanguage: string
  startedAt: number
  finishedAt: number | null
  submittedBy: number
  progress: { done: number, total: number }
}

type Overview = {
  targetLanguages: { code: string, name: string }[]
  jobs: Record<string, Job | null>
  configured: boolean
}

type JobState = { job: Job | null, vtt: string | null }

type VideoInfo = { uuid: string, isLive: boolean }

type Caption = { language: { id: string, label: string }, fileUrl: string, automaticallyGenerated: boolean, updatedAt: string }

type CaptionList = { data: Caption[] }

type SelectOption = { value: string, label: string }

type PanelContext = {
  helpers: Helpers
  video: VideoInfo
  baseUrl: string
  t: Messages
  /** Language name to use inside a sentence ("français" in French) */
  languageName: (code: string) => string
  /** Language name to use as a label, capitalized like PeerTube's caption rows ("Français") */
  languageLabel: (code: string) => string
  /** Status rows, inside PeerTube's caption list */
  rows: HTMLElement
  /** Section after the caption list: title, texts and pickers */
  section: HTMLElement
  form: HTMLElement
  note: HTMLElement
  /** Target languages whose caption is being uploaded */
  saving: Set<string>
  /** Target languages whose caption upload failed */
  saveErrors: Set<string>
  /** Target languages whose caption was uploaded since the page was opened */
  saved: string[]
  pollTimer: ReturnType<typeof setTimeout> | null
}

const ROWS_ID = 'subtitle-translator-rows'
const SECTION_ID = 'subtitle-translator-panel'
// The caption list form of PeerTube's captions page component, and its "Add a caption" button
const CAPTION_LIST_SELECTOR = 'my-video-captions .captions'
const ADD_BUTTON_SELECTOR = '.peertube-create-button'
const CAPTIONS_PAGE = /^\/videos\/manage\/([^/?#]+)\/captions(?:[?#].*)?$/
const POLL_INTERVAL_MS = 3000
const CAPTION_LIST_WAIT_MS = 10000

/**
 * Every text the panel shows, in English. The English text is the translation key looked up in
 * languages/*.json through peertubeHelpers.translate. `{name}` placeholders are filled in after
 * translation.
 */
const MESSAGES = {
  title: 'Translate captions',
  intro: 'Translate one of this video\'s captions with TranslateGemma, then review the result in the caption editor.',
  publishedDirectly: 'The translated caption is published on the video as soon as it is ready.',
  leaveNote: 'You can leave this page: the translation continues, and the caption is published the next time you open this page.',
  from: 'From',
  into: 'Into',
  translate: 'Translate',
  autoGenerated: '{language} (auto-generated)',
  replacesExisting: '{language} (replaces the existing caption)',
  noCaptions: 'This video has no caption to translate yet. Add or generate one first.',
  notConfigured: 'Caption translation is not configured.',
  running: 'Source: {source} · {done} / {total} sentences translated',
  publishing: 'Publishing…',
  published: 'Published just now ✔',
  reloadHint: 'Reload the page to edit this caption.',
  reload: 'Reload page',
  publishFailed: 'Translated, but the caption could not be published.',
  tryAgain: 'Try again',
  dismiss: 'Dismiss',
  publishedNotification: '{target} caption published.',
  replaceTitle: 'Replace the {target} caption?',
  replaceContent: 'This video already has a {target} caption. The translation will replace it.',
  cancel: 'Cancel',
  replace: 'Replace',
  sourceGone: 'The {source} caption no longer exists.',
  requestFailed: 'The translation request failed.',
  interrupted: 'The translation was interrupted by a server restart.',
  jobFailed: 'The translation failed unexpectedly.',
  backendUnreachable: 'The translation service could not be reached.',
  backendError: 'The translation service returned an error.',
  invalidResponse: 'The translation service sent a response the plugin could not read.',
  emptyTranslation: 'The translation service returned an empty translation.'
} as const

type MessageKey = keyof typeof MESSAGES
type Messages = Record<MessageKey, string>

const FAILURE_MESSAGES: Record<FailureStatus, MessageKey> = {
  interrupted: 'interrupted',
  job_failed: 'jobFailed',
  backend_unreachable: 'backendUnreachable',
  backend_error: 'backendError',
  invalid_response: 'invalidResponse',
  empty_translation: 'emptyTranslation'
}

function register ({ registerHook, peertubeHelpers }: RegisterClientOptions): void {
  registerHook({
    target: 'action:router.navigation-end',
    handler: ({ path }: { path: string }) => {
      const match = CAPTIONS_PAGE.exec(path)
      if (!match) return
      mountPanel(peertubeHelpers, decodeURIComponent(match[1]!)).catch(err => {
        console.error('[subtitle-translator] failed to show the translation panel', err)
      })
    }
  })
}

export { register }

