async function mountPanel (helpers: Helpers, videoId: string): Promise<void> {
  const captionList = await waitForElement(CAPTION_LIST_SELECTOR, CAPTION_LIST_WAIT_MS)
  if (!captionList) return

  document.getElementById(ROWS_ID)?.remove()
  document.getElementById(SECTION_ID)?.remove()

  const rows = element('div', 'subtitle-translator-rows')
  rows.id = ROWS_ID
  const section = element('section', 'subtitle-translator-panel')
  section.id = SECTION_ID
  attach(captionList, rows, section)
  keepAttached(videoId, rows, section)

  const video = await requestJson<VideoInfo>(helpers, `/api/v1/videos/${encodeURIComponent(videoId)}`, { method: 'GET', body: null })
  if (video.isLive) {
    rows.remove()
    section.remove()
    return
  }

  const t = await translateMessages(helpers)
  const form = element('div', 'subtitle-translator-form')
  const note = text('p', '', 'subtitle-translator-muted')
  section.replaceChildren(
    text('h3', t.title),
    text('p', t.intro),
    text('p', t.publishedDirectly, 'subtitle-translator-muted'),
    form,
    note
  )

  const pageLanguage = document.documentElement.lang || navigator.language
  const displayNames = new Intl.DisplayNames([ pageLanguage ], { type: 'language', fallback: 'code' })
  const ctx: PanelContext = {
    helpers,
    video,
    baseUrl: `${helpers.getBaseRouterRoute()}/translations/${video.uuid}`,
    t,
    languageName: code => displayNames.of(code) ?? code,
    languageLabel: code => capitalize(displayNames.of(code) ?? code, pageLanguage),
    rows,
    section,
    form,
    note,
    saving: new Set(),
    saveErrors: new Set(),
    saved: [],
    pollTimer: null
  }

  try {
    const [ overview, captions ] = await Promise.all([ fetchOverview(ctx), fetchCaptions(ctx) ])
    renderForm(ctx, overview, captions, pageLanguage)
    await refresh(ctx)
  } catch (err) {
    renderRequestError(ctx, err)
  }
}

/** Places the status rows above PeerTube's "Add a caption" button and the section after the caption list. */
function attach (captionList: HTMLElement, rows: HTMLElement, section: HTMLElement): void {
  const addButton = captionList.querySelector(ADD_BUTTON_SELECTOR)
  const addButtonBlock = Array.from(captionList.children).find(child => addButton && child.contains(addButton)) ?? null
  captionList.insertBefore(rows, addButtonBlock)
  captionList.insertAdjacentElement('afterend', section)
}

/**
 * Re-attaches the rows and the section when Angular re-creates the caption list. Stops when the
 * user is no longer on this video's captions page, or when a newer mount replaced these elements.
 */
function keepAttached (videoId: string, rows: HTMLElement, section: HTMLElement): void {
  const observer = new MutationObserver(() => {
    const match = CAPTIONS_PAGE.exec(window.location.pathname)
    const current = document.getElementById(ROWS_ID)
    if (!match || decodeURIComponent(match[1]!) !== videoId || (current && current !== rows)) {
      observer.disconnect()
      return
    }
    if (rows.isConnected && section.isConnected) return

    const captionList = document.querySelector<HTMLElement>(CAPTION_LIST_SELECTOR)
    if (captionList) attach(captionList, rows, section)
  })
  observer.observe(document.body, { childList: true, subtree: true })
}

/** Reloads the jobs, uploads finished translations and keeps polling while a job runs. */
async function refresh (ctx: PanelContext): Promise<void> {
  if (ctx.pollTimer) clearTimeout(ctx.pollTimer)
  ctx.pollTimer = null
  if (!ctx.rows.isConnected && !ctx.section.isConnected) return

  const overview = await fetchOverview(ctx)
  renderRows(ctx, overview)

  const jobs = Object.values(overview.jobs).filter((job): job is Job => job !== null)
  for (const job of jobs) {
    const code = job.targetLanguage
    if (job.status === 'completed' && !ctx.saving.has(code) && !ctx.saveErrors.has(code)) {
      saveCaption(ctx, code).catch(err => renderRequestError(ctx, err))
    }
  }

  const running = jobs.some(job => job.status === 'running')
  ctx.note.textContent = running ? ctx.t.leaveNote : ''
  if (running) {
    ctx.pollTimer = setTimeout(() => refresh(ctx).catch(err => renderRequestError(ctx, err)), POLL_INTERVAL_MS)
  }
}

function renderForm (ctx: PanelContext, overview: Overview, captions: Caption[], pageLanguage: string): void {
  const { t } = ctx

  if (!overview.configured) {
    ctx.form.replaceChildren(text('p', t.notConfigured, 'subtitle-translator-error'))
    return
  }
  if (captions.length === 0) {
    ctx.form.replaceChildren(text('p', t.noCaptions))
    return
  }

  const existing = new Set(captions.map(caption => caption.language.id))
  const autoGenerated = new Set(captions.filter(caption => caption.automaticallyGenerated).map(caption => caption.language.id))

  const sourceOptions = byLabel(captions.map(caption => {
    const language = ctx.languageLabel(caption.language.id)
    return { value: caption.language.id, label: autoGenerated.has(caption.language.id) ? fill(t.autoGenerated, { language }) : language }
  }))
  const sourceSelect = select(sourceOptions)
  const preferredSource = preferredSourceCaption(captions)
  if (preferredSource) sourceSelect.value = preferredSource.language.id

  const targetSelect = select([])
  const updateTargets = () => {
    const previous = targetSelect.value
    const targetOptions = byLabel(overview.targetLanguages
      .filter(language => language.code !== sourceSelect.value)
      .map(language => {
        const name = ctx.languageLabel(language.code)
        return { value: language.code, label: existing.has(language.code) ? fill(t.replacesExisting, { language: name }) : name }
      }))
    targetSelect.replaceChildren(...targetOptions.map(o => option(o.value, o.label)))
    const preferred = preferredTarget(targetOptions.map(o => o.value), existing, previous, pageLanguage)
    if (preferred) targetSelect.value = preferred
  }
  sourceSelect.addEventListener('change', updateTargets)
  updateTargets()

  const translateButton = button(ctx, t.translate, 'primary', () => confirmAndStart(ctx, sourceSelect.value, targetSelect.value))

  const row = element('div', 'subtitle-translator-pickers')
  row.append(labelled(t.from, sourceSelect), labelled(t.into, targetSelect), translateButton)
  ctx.form.replaceChildren(row)
}

/**
 * The source to preselect: the oldest caption that was not auto-generated, as the original caption
 * usually exists before the translations made from it; null when every caption is auto-generated.
 * The video's language is not used: PeerTube's auto-transcription may set it wrongly (e.g. German
 * for Luxembourgish speech).
 */
function preferredSourceCaption (captions: Caption[]): Caption | null {
  const written = captions.filter(caption => !caption.automaticallyGenerated)
  return [ ...written ].sort((a, b) => Date.parse(a.updatedAt) - Date.parse(b.updatedAt))[0] ?? null
}

/**
 * The target to preselect: the previous choice when it is still offered, else the page language,
 * else the first language (in the order shown) the video has no caption in yet.
 */
function preferredTarget (codes: string[], existing: Set<string>, previous: string, pageLanguage: string): string | null {
  if (codes.includes(previous)) return previous
  const pageBase = pageLanguage.split('-')[0]
  const page = codes.find(code => code === pageLanguage || code === pageBase)
  if (page && !existing.has(page)) return page
  return codes.find(code => !existing.has(code)) ?? null
}

function renderRows (ctx: PanelContext, overview: Overview): void {
  const { t } = ctx
  const rows: HTMLElement[] = []

  for (const job of Object.values(overview.jobs)) {
    if (!job) continue
    const target = ctx.languageLabel(job.targetLanguage)

    if (job.status === 'running') {
      const { done, total } = job.progress
      rows.push(statusRow(target, [
        text('span', fill(t.running, { source: ctx.languageLabel(job.sourceLanguage), done, total })),
        progressBar(done, total)
      ], []))
      continue
    }

    if (job.status === 'completed') {
      if (!ctx.saveErrors.has(job.targetLanguage)) {
        rows.push(statusRow(target, [ text('span', t.publishing), progressBar(null, null) ], []))
        continue
      }
      rows.push(statusRow(target, [ text('span', t.publishFailed, 'subtitle-translator-error') ], [
        button(ctx, t.tryAgain, 'secondary', async () => {
          ctx.saveErrors.delete(job.targetLanguage)
          await refresh(ctx)
        })
      ]))
      continue
    }

    rows.push(statusRow(target, [ text('span', t[FAILURE_MESSAGES[job.status]], 'subtitle-translator-error') ], [
      button(ctx, t.tryAgain, 'secondary', () => confirmAndStart(ctx, job.sourceLanguage, job.targetLanguage)),
      button(ctx, t.dismiss, 'secondary', async () => {
        await requestNoContent(ctx.helpers, `${ctx.baseUrl}/${job.targetLanguage}`, { method: 'DELETE' })
        await refresh(ctx)
      })
    ]))
  }

  for (const code of ctx.saved) {
    rows.push(statusRow(ctx.languageLabel(code), [
      text('span', t.published),
      text('span', t.reloadHint, 'subtitle-translator-muted')
    ], [
      button(ctx, t.reload, 'secondary', async () => window.location.reload())
    ]))
  }

  ctx.rows.replaceChildren(...rows)
}

async function confirmAndStart (ctx: PanelContext, sourceLanguage: string, targetLanguage: string): Promise<void> {
  const captions = await fetchCaptions(ctx)
  const sourceCaption = captions.find(caption => caption.language.id === sourceLanguage)
  if (!sourceCaption) throw new Error(fill(ctx.t.sourceGone, { source: ctx.languageName(sourceLanguage) }))

  if (!captions.some(caption => caption.language.id === targetLanguage)) return startTranslation(ctx, sourceCaption, targetLanguage)

  const target = ctx.languageName(targetLanguage)
  ctx.helpers.showModal({
    title: fill(ctx.t.replaceTitle, { target }),
    content: fill(ctx.t.replaceContent, { target }),
    cancel: { value: ctx.t.cancel },
    confirm: {
      value: ctx.t.replace,
      action: () => {
        startTranslation(ctx, sourceCaption, targetLanguage).catch(err => renderRequestError(ctx, err))
      }
    }
  })
}

async function startTranslation (ctx: PanelContext, sourceCaption: Caption, targetLanguage: string): Promise<void> {
  const response = await fetch(sourceCaption.fileUrl, { headers: authHeaders(ctx.helpers) })
  if (!response.ok) throw new Error(await describeFailure('GET', sourceCaption.fileUrl, response))
  const vtt = await response.text()

  ctx.saved = ctx.saved.filter(code => code !== targetLanguage)
  ctx.saveErrors.delete(targetLanguage)
  await requestJson<{ job: Job }>(ctx.helpers, ctx.baseUrl, {
    method: 'POST',
    body: { sourceLanguage: sourceCaption.language.id, targetLanguage, vtt }
  })
  await refresh(ctx)
}

async function saveCaption (ctx: PanelContext, targetLanguage: string): Promise<void> {
  ctx.saving.add(targetLanguage)
  try {
    const state = await requestJson<JobState>(ctx.helpers, `${ctx.baseUrl}/${targetLanguage}`, { method: 'GET', body: null })
    if (!state.vtt) throw new Error(`The ${targetLanguage} translation has no WebVTT to save (job status: ${state.job?.status ?? 'none'})`)

    const body = new FormData()
    body.append('captionfile', new Blob([ state.vtt ], { type: 'text/vtt' }), `${targetLanguage}.vtt`)
    const url = `/api/v1/videos/${ctx.video.uuid}/captions/${targetLanguage}`
    const response = await fetch(url, { method: 'PUT', headers: authHeaders(ctx.helpers), body })

    if (!response.ok) {
      console.error('[subtitle-translator] caption upload failed', { url, status: response.status, body: (await response.text()).slice(0, 300) })
      ctx.saveErrors.add(targetLanguage)
    } else {
      await requestNoContent(ctx.helpers, `${ctx.baseUrl}/${targetLanguage}`, { method: 'DELETE' })
      ctx.saved = [ ...ctx.saved, targetLanguage ]
      ctx.helpers.notifier.success(fill(ctx.t.publishedNotification, { target: ctx.languageName(targetLanguage) }))
    }
  } finally {
    ctx.saving.delete(targetLanguage)
  }
  await refresh(ctx)
}

/**
 * Shows a failed plugin or PeerTube request in the section, with a way to try again. The error
 * itself goes to the browser console only.
 */
function renderRequestError (ctx: PanelContext, err: unknown): void {
  console.error('[subtitle-translator] request failed', err)
  ctx.note.replaceChildren(
    text('span', ctx.t.requestFailed, 'subtitle-translator-error'),
    buttonRow([ button(ctx, ctx.t.tryAgain, 'secondary', () => refresh(ctx)) ])
  )
}

